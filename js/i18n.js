(function () {
  const STORAGE_KEY = "akhmeteli.lang";
  const SUPPORTED = ["ka", "en", "ru"];
  const DEFAULT = "ka";

  function getLang() {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && SUPPORTED.includes(saved)) return saved;
    return DEFAULT;
  }

  function setLang(lang) {
    if (!SUPPORTED.includes(lang)) return;
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.setAttribute("lang", lang);
    apply();
    document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
  }

  function t(key) {
    const lang = getLang();
    const dict = window.I18N_DICT[lang] || {};
    return dict[key] !== undefined ? dict[key] : key;
  }

  function tField(field) {
    if (!field) return "";
    const lang = getLang();
    return field[lang] || field.en || "";
  }

  function apply(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      el.textContent = t(key);
    });
    root.querySelectorAll("[data-i18n-attr]").forEach(el => {
      const spec = el.getAttribute("data-i18n-attr"); // format: "attr:key,attr:key"
      spec.split(",").forEach(pair => {
        const [attr, key] = pair.split(":").map(s => s.trim());
        if (attr && key) el.setAttribute(attr, t(key));
      });
    });
  }

  window.I18N = { getLang, setLang, t, tField, apply, SUPPORTED };

  document.addEventListener("DOMContentLoaded", () => {
    document.documentElement.setAttribute("lang", getLang());
    apply();
  });
})();
